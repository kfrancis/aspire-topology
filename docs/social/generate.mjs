// Builds the GitHub social preview card.
//
// The isometric icons are read out of the renderer's own snapshot rather than redrawn here, so the
// card can never drift from what AspireTopology actually produces.
//
//   node docs/social/generate.mjs
//   chrome --headless=new --window-size=1280,640 \
//     --screenshot=docs/images/social-preview.png docs/social/social-preview.html
//
// GitHub renders the card at 1280x640 and crops toward the centre on some surfaces, so everything
// that matters stays inside a 40pt border. Capture at device scale 1: the gradients and grid do not
// compress well, and a 2x capture lands above GitHub's 1MB limit for a social preview.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..');

const snapshot = JSON.parse(
  readFileSync(join(repoRoot, 'tests', 'snapshots', 'postgres-redis.isoflow.json'), 'utf8'),
);

const iconUrl = (kind) => {
  const icon = snapshot.icons.find((candidate) => candidate.id === `aspire-topology-${kind}`);

  if (!icon) {
    throw new Error(`The snapshot has no ${kind} icon. Regenerate the snapshots first.`);
  }

  return icon.url;
};

const palette = {
  purple: '#512bd4',
  primary: '#7455dd',
  secondary: '#b9aaee',
  black: '#1f1e33',
  grey: '#dce0e8',
  muted: '#66697e',
};

/** Nodes of the little diagram on the right, in a 520 x 440 box. */
const nodes = [
  { id: 'web', kind: 'service', x: 260, y: 26, label: 'web' },
  { id: 'api', kind: 'service', x: 260, y: 172, label: 'api' },
  { id: 'appdb', kind: 'database', x: 116, y: 318, label: 'appdb' },
  { id: 'cache', kind: 'cache', x: 404, y: 318, label: 'cache' },
];

const edges = [
  { from: 'web', to: 'api', dashed: false },
  { from: 'api', to: 'appdb', dashed: false },
  { from: 'api', to: 'cache', dashed: false },
];

const byId = Object.fromEntries(nodes.map((node) => [node.id, node]));
const size = 112;
const centre = (node) => ({ x: node.x + size / 2, y: node.y + size * 0.52 });

const lines = edges
  .map((edge) => {
    const from = centre(byId[edge.from]);
    const to = centre(byId[edge.to]);

    return `<line x1="${from.x}" y1="${from.y}" x2="${to.x}" y2="${to.y}"
      stroke="${edge.dashed ? palette.grey : palette.purple}"
      stroke-width="${edge.dashed ? 4 : 5}"
      stroke-linecap="round"
      ${edge.dashed ? 'stroke-dasharray="2 14"' : ''} />`;
  })
  .join('\n      ');

const tiles = nodes
  .map(
    (node) => `
      <figure class="node" style="left: ${node.x}px; top: ${node.y}px; width: ${size}px">
        <img src="${iconUrl(node.kind)}" alt="" width="${size}" height="${size}" />
        <figcaption>${node.label}</figcaption>
      </figure>`,
  )
  .join('');

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <title>AspireTopology</title>
    <style>
      /* Generated by docs/social/generate.mjs. Edit that, not this. */
      * { box-sizing: border-box; margin: 0; padding: 0; }

      body {
        width: 1280px;
        height: 640px;
        overflow: hidden;
        font-family: Poppins, "Segoe UI Variable Display", "Segoe UI", system-ui, sans-serif;
        color: ${palette.black};
        background: #ffffff;
      }

      .card {
        position: relative;
        width: 1280px;
        height: 640px;
        display: flex;
        align-items: center;
        /* The 40pt safe border GitHub asks for, plus a little more. */
        padding: 64px;
        background:
          radial-gradient(760px 520px at 88% 6%, rgba(116, 85, 221, 0.16), transparent 62%),
          radial-gradient(560px 420px at 4% 96%, rgba(81, 43, 212, 0.09), transparent 60%),
          linear-gradient(135deg, #ffffff 38%, #f4f1fd 100%);
      }

      /* The isometric grid Isoflow draws behind a diagram, faintly. */
      .card::before {
        content: "";
        position: absolute;
        inset: 0;
        background-image:
          repeating-linear-gradient(26.57deg, ${palette.grey} 0 1px, transparent 1px 52px),
          repeating-linear-gradient(-26.57deg, ${palette.grey} 0 1px, transparent 1px 52px);
        opacity: 0.5;
        mask-image: radial-gradient(circle at 62% 46%, #000 0%, transparent 78%);
      }

      .card > * { position: relative; }

      .copy { width: 640px; flex: 0 0 auto; }

      .eyebrow {
        display: inline-flex;
        align-items: center;
        gap: 10px;
        font-size: 17px;
        font-weight: 600;
        letter-spacing: 0.16em;
        text-transform: uppercase;
        color: ${palette.purple};
      }

      .eyebrow::before {
        content: "";
        width: 14px;
        height: 14px;
        border-radius: 50%;
        background: linear-gradient(135deg, ${palette.purple}, ${palette.primary});
      }

      h1 {
        margin-top: 22px;
        font-size: 78px;
        line-height: 1.02;
        font-weight: 700;
        letter-spacing: -0.035em;
      }

      h1 span { color: ${palette.purple}; }

      p {
        margin-top: 20px;
        font-size: 27px;
        line-height: 1.42;
        color: ${palette.muted};
        max-width: 30ch;
      }

      .chips { display: flex; gap: 12px; margin-top: 34px; flex-wrap: wrap; }

      .chip {
        font-family: "Fira Code", ui-monospace, SFMono-Regular, Consolas, monospace;
        font-size: 19px;
        padding: 11px 18px;
        border-radius: 10px;
        background: #ffffff;
        border: 1px solid ${palette.grey};
        box-shadow: 0 2px 10px rgba(31, 30, 51, 0.06);
      }

      .chip--accent {
        color: #ffffff;
        background: linear-gradient(135deg, ${palette.purple}, ${palette.primary});
        border-color: transparent;
      }

      .diagram {
        position: relative;
        width: 520px;
        height: 440px;
        margin-left: auto;
        margin-right: 8px;
      }

      .diagram svg { position: absolute; inset: 0; overflow: visible; }

      .node { position: absolute; text-align: center; }

      .node img { display: block; filter: drop-shadow(0 10px 16px rgba(31, 30, 51, 0.18)); }

      .node figcaption {
        margin-top: 2px;
        font-size: 18px;
        font-weight: 600;
        color: ${palette.black};
      }
    </style>
  </head>
  <body>
    <div class="card">
      <div class="copy">
        <span class="eyebrow">Aspire integration</span>
        <h1>Aspire<span>Topology</span></h1>
        <p>Architecture diagrams generated from your Aspire AppHost.</p>
        <div class="chips">
          <code class="chip chip--accent">builder.AddTopologyDiagram();</code>
          <code class="chip">aspire do topology</code>
        </div>
      </div>

      <div class="diagram">
        <svg viewBox="0 0 520 440" width="520" height="440" aria-hidden="true">
          ${lines}
        </svg>
        ${tiles}
      </div>
    </div>
  </body>
</html>
`;

const out = join(here, 'social-preview.html');
writeFileSync(out, html, 'utf8');
console.log('wrote', out);
